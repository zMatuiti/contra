import { chromium } from '@playwright/test';
const browser=await chromium.launch({channel:'chrome'});
const page=await browser.newPage({viewport:{width:1440,height:1100}});
await page.goto('http://127.0.0.1:4173');
await page.getByRole('button',{name:'Enable captions'}).click();
await page.getByRole('button',{name:'Play',exact:true}).last().click();
await page.waitForTimeout(700);
await page.getByRole('button',{name:'Pause',exact:true}).last().focus();
await page.keyboard.press('Enter');
await page.locator('#player').screenshot({path:'design/implementation/captions.png'});
await page.getByRole('button',{name:'Playback speed',exact:true}).click();
await page.locator('#player').screenshot({path:'design/implementation/speed-menu.png'});
await page.keyboard.press('Escape');
await page.getByRole('slider',{name:'Seek',exact:true}).focus();
await page.locator('#player').screenshot({path:'design/implementation/focus.png'});
await page.setViewportSize({width:390,height:844});
await page.locator('#player').screenshot({path:'design/implementation/mobile-captions.png'});
console.log('Saved captions, speed menu and keyboard focus captures from production build.');
await browser.close();
